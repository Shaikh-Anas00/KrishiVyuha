class PortfolioRequest(BaseModel):
    """
    Incoming JSON payload from the Next.js frontend.

    All fields are validated by Pydantic before the request handler runs,
    so the optimizer never receives malformed inputs.

    Weather fields (rainfall_mm, temperature_c, climate_regime) are **optional** —
    if omitted, the system auto-detects them from the NOAA ONI index and historical
    district/season medians (Agro-Climatic Advisory Engine).
    """

    state              : str   = Field(..., example="Maharashtra",
                                       description="Indian state name (title-case)")
    district           : str   = Field(..., example="Pune",
                                       description="District within the state (title-case)")
    season             : str   = Field(..., example="Kharif",
                                       description="Crop season: Kharif | Rabi | Summer | Zaid | Whole Year | Winter | Autumn")
    land_area_ha       : float = Field(..., gt=0, le=10_000, example=5.0,
                                       description="Total cultivable land area in hectares (must be > 0)")
    survival_budget_inr: float = Field(..., ge=0, example=100_000.0,
                                       description="Minimum acceptable worst-case revenue (INR).")
    irrigation_type    : str   = Field("Rainfed", example="Rainfed",
                                       description="Irrigation access: 'Rainfed' | 'Well_Borewell' | 'Canal_River'")
    risk_aversion      : float = Field(1.0, ge=0.0, le=5.0, example=1.0,
                                       description="Markowitz risk aversion (lambda): 0=pure profit, 1=balanced, 2+=defensive diversification")

    # ── Optional weather overrides (auto-detected if None) ────────────────────
    rainfall_mm     : Optional[float] = Field(None, ge=0, le=5_000, example=700.0,
                                              description="Manual override: seasonal rainfall (mm). Auto-detected if omitted.")
    temperature_c   : Optional[float] = Field(None, ge=0, le=60,    example=28.5,
                                              description="Manual override: average temperature (°C). Auto-detected if omitted.")
    climate_regime  : Optional[str]   = Field(None, example="Normal",
                                              description="Manual override: ENSO regime. Auto-detected from NOAA ONI if omitted.")

    available_crops : list[str] = Field(
        ...,
        min_length=1,
        max_length=20,
        example=["Rice", "Cotton", "Soyabean"],
        description="List of crop names the farmer wants to consider. Min 1, max 20."
    )

    @validator("season")
    def validate_season(cls, v: str) -> str:
        if v not in VALID_SEASONS:
            raise ValueError(
                f"Invalid season '{v}'. Must be one of: {sorted(VALID_SEASONS)}"
            )
        return v

    @validator("climate_regime", pre=True, always=True)
    def validate_regime(cls, v: Optional[str]) -> Optional[str]:
        if v is not None and v not in VALID_REGIMES:
            raise ValueError(
                f"Invalid climate_regime '{v}'. Must be one of: {sorted(VALID_REGIMES)}"
            )
        return v

    @validator("irrigation_type")
    def validate_irrigation(cls, v: str) -> str:
        valid = {"Rainfed", "Well_Borewell", "Canal_River"}
        if v not in valid:
            raise ValueError(f"Invalid irrigation_type '{v}'. Must be one of: {sorted(valid)}")
        return v

    @validator("available_crops", each_item=True)
    def validate_crops(cls, v: str) -> str:
        if v not in AVAILABLE_CROPS:
            raise ValueError(
                f"Unknown crop '{v}'. See GET /api/crops for the supported list."
            )
        return v

    class Config:
        schema_extra = {
            "example": {
                "state"              : "Maharashtra",
                "district"           : "Pune",
                "season"             : "Kharif",
                "land_area_ha"       : 5.0,
                "survival_budget_inr": 100_000.0,
                "irrigation_type"    : "Rainfed",
                "available_crops"    : ["Rice", "Cotton", "Soyabean"],
                # rainfall_mm / temperature_c / climate_regime omitted → auto-detected
            }
        }


class CropDetail(BaseModel):
    """Financial breakdown for a single crop in the optimised portfolio."""
    expected_yield    : float = Field(..., description="ML-predicted expected yield (t/ha)")
    worst_case_yield  : float = Field(..., description="Expected yield minus Confidence Margin, floored at 0 (t/ha)")
    market_price      : float = Field(..., description="Market price (INR per tonne)")
    expected_revenue  : float = Field(..., description="Expected revenue for this crop's area allocation (INR)")
    worst_case_revenue: float = Field(..., description="Worst-case revenue before insurance (INR)")
    pmfby_payout      : float = Field(..., description="PMFBY insurance payout if worst-case trigger fires (INR)")
    premium_cost      : float = Field(..., description="Farmer's PMFBY premium (INR)")
    net_worst_case    : float = Field(..., description="Net worst-case income after insurance (INR)")


class PortfolioResponse(BaseModel):
    """
    Complete portfolio optimisation result returned to the frontend.

    The frontend should display:
      - `weights`               as a pie chart / allocation table
      - `expected_income`       as the headline optimistic figure
      - `worst_case_income`     as the guaranteed floor (highlighted if < survival_budget)
      - `total_premium`         as the insurance cost to budget for
      - `crop_details`          for the per-crop breakdown table
      - `climate_info`          to show the auto-detected weather parameters
      - `agronomic_diagnostics` as the explainability text per crop
    """
    success               : bool             = Field(..., description="True if SLSQP fully converged with all constraints satisfied")
    budget_met            : bool             = Field(..., description="True if worst-case income >= survival budget")
    message               : str              = Field(..., description="Human-readable optimizer status message")
    weights               : dict[str, float] = Field(..., description="Optimal fraction of total land per crop (sums to 1.0)")
    area_ha               : dict[str, float] = Field(..., description="Optimal hectares per crop")
    expected_income       : float            = Field(..., description="Total expected portfolio revenue (INR)")
    worst_case_income     : float            = Field(..., description="Worst-case portfolio revenue after PMFBY payouts (INR)")
    total_premium         : float            = Field(..., description="Total PMFBY insurance premium cost (INR)")
    net_expected_profit   : float            = Field(..., description="expected_income - total_premium (INR)")
    portfolio_volatility_inr: float          = Field(0.0, description="Markowitz portfolio revenue standard deviation (INR)")
    sharpe_ratio          : float            = Field(0.0, description="Risk-adjusted return ratio over survival budget")
    risk_aversion         : float            = Field(1.0, description="Markowitz risk aversion lambda used")
    proxied_crops         : dict[str, str]   = Field(default_factory=dict, description="Active crops estimated via proxy")
    crop_details          : dict[str, Any]   = Field(..., description="Per-crop financial + agronomic breakdown")
    optimizer_status      : str              = Field(..., description="Raw scipy optimizer termination message")
    climate_info          : dict[str, Any]   = Field(..., description="Auto-detected climate: regime, rainfall, temperature, ONI")
    agronomic_diagnostics : dict[str, Any]   = Field(..., description="Per-crop agronomic suitability reasons for the explainability panel")
    agmarknet_price_risk  : dict[str, Any]   = Field(default_factory=dict, description="Per-crop Agmarknet modal price risk profiles and natural hedge metrics")



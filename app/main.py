@app.post(
    "/api/optimize",
    response_model = PortfolioResponse,
    summary        = "Optimise Crop Portfolio",
    tags           = ["Optimization"],
    responses      = {
        200: {"description": "Optimisation succeeded; portfolio allocation returned."},
        400: {"description": "Bad request -- impossible budget, unknown crop, or optimizer diverged."},
        422: {"description": "Validation error -- check request field types and allowed values."},
        500: {"description": "Unexpected server error -- check API logs."},
    },
)
def optimize(request: PortfolioRequest) -> PortfolioResponse:
    """
    **Core portfolio optimisation endpoint.**

    Accepts farmer parameters, runs the full ML + SciPy pipeline, and returns
    the risk-optimal land allocation across the selected crops.

    ### How it works (for Swagger UI readers)
    1. **Yield Prediction** – The trained `LinearRegression` model predicts the
       expected yield (t/ha) for each crop under the given weather conditions.
    2. **Worst-Case Yield** – `worst_case = max(0, expected - confidence_margin)`,
       where `confidence_margin = std(residuals)` from the test-set evaluation.
    3. **PMFBY Insurance** – If the worst-case yield falls below 20% of the expected
       yield, the PMFBY parametric insurance payout is triggered automatically.
    4. **SciPy SLSQP Optimisation** – Maximises `sum(w_i * E[yield_i] * price_i * area) - premiums`
       subject to: (a) weights sum to 1.0, (b) each weight ∈ [0, 1],
       (c) worst-case portfolio revenue ≥ `survival_budget_inr`.

    ### Example curl
    ```bash
    curl -X POST http://localhost:8000/api/optimize \\
         -H "Content-Type: application/json" \\
         -d '{
           "state": "Maharashtra", "district": "Pune",
           "season": "Kharif", "land_area_ha": 5,
           "survival_budget_inr": 100000,
           "rainfall_mm": 700, "temperature_c": 28.5,
           "climate_regime": "Normal",
           "available_crops": ["Rice", "Cotton", "Soyabean"]
         }'
    ```

    ### On partial success
    If the survival budget constraint cannot be satisfied (e.g., budget is
    mathematically higher than any achievable worst-case), the optimizer returns
    `success: false` with a best-effort allocation and a descriptive `message`.
    The frontend should surface this as a warning banner rather than an error.
    """
    log.info(
        "Optimize request | state=%s district=%s crops=%s area=%.1f ha budget=%.0f INR",
        request.state, request.district, request.available_crops,
        request.land_area_ha, request.survival_budget_inr,
    )

    try:
        result: dict = optimize_portfolio(
            state           = request.state,
            district        = request.district,
            season          = request.season,
            crops           = request.available_crops,
            total_area_ha   = request.land_area_ha,
            survival_budget = request.survival_budget_inr,
            risk_aversion   = request.risk_aversion,
            rainfall        = request.rainfall_mm,         # None → auto-detected
            temperature     = request.temperature_c,       # None → auto-detected
            climate_regime  = request.climate_regime,      # None → auto-detected
            irrigation_type = request.irrigation_type,
            verbose         = False,
        )

    except FileNotFoundError as exc:
        log.error("Model artefact missing: %s", exc)
        raise HTTPException(
            status_code = 500,
            detail      = (
                "Required ML model artefact not found. "
                "Please run `python src/yield_predictor.py` first. "
                f"Details: {exc}"
            ),
        )

    except ValueError as exc:
        log.warning("ValueError in optimizer: %s", exc)
        raise HTTPException(status_code=400, detail=str(exc))

    except Exception as exc:
        log.exception("Unexpected error during optimization: %s", exc)
        raise HTTPException(
            status_code = 500,
            detail      = f"Internal optimization error: {exc}",
        )

    net_expected_profit = round(result["expected_income"] - result["total_premium"], 2)

    log.info(
        "Optimize success | expected=INR %.0f worst_case=INR %.0f premium=INR %.0f budget_met=%s",
        result["expected_income"], result["worst_case_income"],
        result["total_premium"], result.get("budget_met", "?"),
    )

    # Identify active proxied crops for explainability warnings
    active_proxies = {c: note for c, note in PROXIED_CROPS.items() if c in request.available_crops}

    return PortfolioResponse(
        success                  = result["success"],
        budget_met               = result.get("budget_met", result["worst_case_income"] >= request.survival_budget_inr),
        message                  = result["message"],
        weights                  = result["weights"],
        area_ha                  = result["area_ha"],
        expected_income          = result["expected_income"],
        worst_case_income        = result["worst_case_income"],
        total_premium            = result["total_premium"],
        net_expected_profit      = net_expected_profit,
        portfolio_volatility_inr = result.get("portfolio_volatility_inr", 0.0),
        sharpe_ratio             = result.get("sharpe_ratio", 0.0),
        risk_aversion            = result.get("risk_aversion", request.risk_aversion),
        proxied_crops            = active_proxies,
        crop_details             = result["crop_details"],
        optimizer_status         = result["optimizer_status"],
        climate_info             = result.get("climate_info", {}),
        agronomic_diagnostics    = result.get("agronomic_diagnostics", {}),
        agmarknet_price_risk     = result.get("agmarknet_price_risk", {}),
    )



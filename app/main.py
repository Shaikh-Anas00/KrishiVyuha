class RotationRequest(PortfolioRequest):
    n_seasons        : int   = Field(3, ge=2, le=5, description="Number of consecutive seasons to plan")
    previous_weights : Optional[dict[str, float]] = Field(
        None, description="Land share by crop grown LAST season, e.g. {'Cotton': 1.0}. Omit if unknown.")
    discount         : float = Field(0.95, gt=0, le=1.0, description="Per-season discount factor")


@app.post("/api/rotation", tags=["Optimization"], summary="Multi-season rotation-aware plan")
def rotation(request: RotationRequest) -> dict:
    """
    Plans `n_seasons` consecutive seasons jointly using a crop-interaction matrix
    (legume N-credit, same-family disease build-up, monoculture penalty).
    Returns the rotation-aware plan plus two baselines: the static single-season
    plan repeated on the same plots, and a greedy season-by-season plan.
    The interaction matrix is an agronomic prior, not fitted from data.
    """
    from src.rotation_optimizer import optimize_rotation
    try:
        return optimize_rotation(
            state=request.state, district=request.district, season=request.season,
            crops=request.available_crops, total_area_ha=request.land_area_ha,
            survival_budget=request.survival_budget_inr, n_seasons=request.n_seasons,
            previous_weights=request.previous_weights,
            rainfall=request.rainfall_mm, temperature=request.temperature_c,
            climate_regime=request.climate_regime, irrigation_type=request.irrigation_type,
            risk_aversion=request.risk_aversion, discount=request.discount,
        )
    except ValueError as exc:
        raise HTTPException(status_code=400, detail=str(exc))
    except Exception as exc:
        log.exception("Rotation optimisation error: %s", exc)
        raise HTTPException(status_code=500, detail=f"Internal rotation error: {exc}")



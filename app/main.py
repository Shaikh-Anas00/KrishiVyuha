@app.get(
    "/api/climate-preview",
    summary = "Auto-Detect Climate for District + Season",
    tags    = ["Reference Data"],
    responses={
        200: {"description": "Climate auto-detection succeeded."},
        500: {"description": "Failed to read climate data files."},
    },
)
def climate_preview(
    district: str = Query(..., example="Pune",   description="District name (title-case)"),
    season  : str = Query(..., example="Kharif", description="Season string"),
    state   : Optional[str] = Query(None, example="Maharashtra", description="State (optional, improves fallback lookup)"),
) -> dict:
    """
    **Live climate preview for a given district and season.**

    Reads the latest NOAA ONI anomaly to classify the current ENSO regime
    (El Niño / La Niña / Normal), then queries the historical district/season
    median rainfall and temperature from the master dataset, applies ENSO
    adjustments, and returns the adjusted values.

    The Next.js frontend calls this endpoint immediately when the farmer
    selects a District + Season combination, before running the full
    optimisation. The response is displayed as a live badge:

        🟢 Live Sync: El Niño detected | District Baseline: 862.9 mm, 28.8°C

    ```
    GET /api/climate-preview?district=Pune&season=Kharif&state=Maharashtra
    ```
    """
    try:
        data = auto_detect_climate_and_weather(district, season, state)
        return {
            "district"        : district,
            "season"          : season,
            "climate_regime"  : data["climate_regime"],
            "oni_value"       : data["oni_value"],
            "rainfall_mm"     : data["rainfall_mm"],
            "temperature_c"   : data["temperature_c"],
            "baseline_source" : data["baseline_source"],
            "baseline_rain"   : data["baseline_rain"],
            "baseline_temp"   : data["baseline_temp"],
            "enso_rain_adj_pct": data["enso_rain_adj_pct"],
            "enso_temp_adj_c"  : data["enso_temp_adj_c"],
            "note"            : (
                f"Values auto-adjusted for {data['climate_regime']} regime. "
                f"Source: {data['baseline_source']}."
            ),
        }
    except FileNotFoundError as exc:
        raise HTTPException(status_code=500, detail=f"Climate data file missing: {exc}")
    except Exception as exc:
        log.exception("Climate preview error: %s", exc)
        raise HTTPException(status_code=500, detail=f"Climate detection error: {exc}")


